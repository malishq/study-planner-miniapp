from __future__ import annotations

from typing import List, Optional, Tuple

BOT_NAME = "Учебный планер"
MENU_BUTTON_TEXT = "Планер"
OPEN_BUTTON_TEXT = "Открыть планер"

BOT_SHORT_DESCRIPTION = "Предметы, дедлайны и несданные работы в одном мини-приложении."

BOT_DESCRIPTION = (
    "Учебный планер держит в одном месте предметы, задания с дедлайнами и их статусы. "
    "Показывает, что сдать на этой неделе, что просрочено и как идёт прогресс по каждому курсу. "
    "Данные хранятся в вашем Telegram, регистрация не нужна."
)

COMMANDS: List[Tuple[str, str]] = [
    ("start", "Открыть планер"),
    ("help", "Как пользоваться"),
    ("about", "О приложении"),
]


def greeting_name(first_name: Optional[str]) -> str:
    name = (first_name or "").strip()
    return f", {name}" if name else ""


def start_text(first_name: Optional[str] = None) -> str:
    return (
        f"Привет{greeting_name(first_name)}! Это {BOT_NAME}.\n\n"
        "Добавьте предметы и задания с дедлайнами, отмечайте сданное и смотрите, "
        "что горит на этой неделе. Планер открывается кнопкой ниже или через меню слева от поля ввода."
    )


def help_text() -> str:
    return (
        "Как это работает:\n\n"
        "1. Откройте планер кнопкой «Открыть планер» или через кнопку меню.\n"
        "2. Создайте предметы: название, преподаватель, зачёт или экзамен.\n"
        "3. Добавьте задания с дедлайнами: практики, лабораторные, тесты, курсовые, рабочие тетради.\n"
        "4. Отмечайте сданное одним нажатием, ставьте оценки после проверки.\n\n"
        "Экран «Неделя» показывает ближайшие дедлайны, «Несданное» — всё, что ещё не сдано, по срокам. "
        "В настройках есть экспорт и импорт данных в JSON.\n\n"
        "Команды: /start — открыть планер, /help — эта подсказка, /about — о приложении."
    )


def about_text(webapp_url: str) -> str:
    return (
        f"{BOT_NAME} — мини-приложение Telegram для студентов.\n\n"
        "Данные остаются у вас: они хранятся в облачном хранилище Telegram и доступны на всех ваших устройствах. "
        "У бота нет базы данных и доступа к вашим записям.\n\n"
        f"Веб-версия: {webapp_url}"
    )


def fallback_text() -> str:
    return "Я умею только открывать планер. Нажмите кнопку ниже или отправьте /help."
